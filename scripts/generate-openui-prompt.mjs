#!/usr/bin/env node
/**
 * generate-openui-prompt.mjs — regenerate the OpenUI Lang component prompt
 * for the pm-designer-openui skill from the OFFICIAL component library.
 *
 * The component table is generated from @openuidev/react-ui's openuiLibrary
 * (imported from the lean `genui-lib` entry — no chat/artifact surface) via
 * its own `prompt()`; openuiPromptOptions' official examples and rules are
 * kept, and DeepOrca layers product-specific rules on top (single interactive
 * app with $page navigation, the design.* tool whitelist, the excess-args
 * arity hard rule). Nothing component-level is hand-maintained here.
 *
 * The renderer side (packages/desktop/src/renderer/openui/OpenuiRenderer.tsx)
 * renders with the SAME openuiLibrary, so prompt and runtime stay in lockstep
 * — the prompt is generated by the same @openuidev/lang-core version the
 * installed @openuidev/react-lang parses with (caret ranges, kept aligned by
 * package-lock.json).
 *
 * Usage:
 *   npm run openui:prompt            # --write, update SKILL.md in place
 *   node scripts/generate-openui-prompt.mjs           # print to stdout
 *   node scripts/generate-openui-prompt.mjs --write    # update SKILL.md
 *
 * The desktop build regenerates and fails on drift (see packages/desktop/build.mjs).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");

export const SKILL_PATH = join(repoRoot, "packages/core/templates/plugins/design/skills/pm-designer-openui/SKILL.md");

/** DeepOrca product rules layered on top of openuiPromptOptions. */
export const DESIGNER_ADDITIONAL_RULES = [
  "Follow the taste skill's design discipline (one accent, 4/8px spacing, ≥4.5:1 contrast).",
  "Use Query('design.readWiki', {name: '...'}) to pull project context into prototypes.",
  // Real-machine 2026-09-07: the model kept passing extra positional args
  // to Card/Stack — every excess arg is DROPPED (excess-args warnings on
  // the canvas). Arity is a hard rule, not a suggestion.
  "NEVER pass more arguments than the component signature above shows — extra positional arguments are DROPPED by the compiler (excess-args). Pass options through their named props only, and omit props you don't need.",
  // 2026-09-07: prototypes must be ONE directly interactive application
  // driven by $page state, not scattered per-page screens. Layers with the
  // official rule that prefers Tabs/Modal over ternaries: that rule governs
  // IN-PAGE sections; PAGE-level navigation stays on the $page shell.
  'The prototype is ONE interactive application, never a stack of separate screens. Declare `$page = "<first-page>"`, give each page of the requirements document its own view variable, and render exactly one of them in root behind a ternary (e.g. `$page == "orders" ? ordersView : null`). Keep a persistent navigation shell that is visible on every page. (The Tabs/Accordion/Modal preference applies to in-page sections, not to page-level navigation.)',
  'Wire all navigation and flows through button actions: `Button("登录", Action([@Set($page, "orders")]))`. Every page and flow in the requirements must be reachable through such actions — buttons may chain multiple steps like `Action([@Set($page, "detail"), @Reset($form)])`.',
  // 2026-09-07: a bare-string action (`Button("Sign In", "submit:login")`)
  // parses cleanly against the official schema (action is a passthrough) but
  // the official Button forwards the string to triggerAction's third arg,
  // where react-lang throws on `"steps" in action` — a silent dead button
  // (no red wall, no correction-loop input). Action expressions only.
  'Button actions MUST be Action([...]) expressions (e.g. `Action([@Set($page, "home")])`). NEVER pass a bare string as a button action — it compiles, but the button silently does nothing when clicked.',
  "Buttons inside @Each must be written inline in the template (assigning a Button to a variable and reusing it inside @Each duplicates the last item's context).",
];

/** One compact single-app navigation example, in official component arity. */
export const DESIGNER_EXAMPLE = [
  "Example — one interactive app with page navigation (NEVER one screen per page):",
  "```",
  '$page = "home"',
  'root = Stack([nav, $page == "home" ? homeView : ordersView])',
  'nav = Stack([Button("首页", Action([@Set($page, "home")])), Button("订单", Action([@Set($page, "orders")]))], "row")',
  'homeView = Card([CardHeader("概览"), TextContent("今日订单 128", "large-heavy")])',
  'ordersView = Card([CardHeader("订单列表"), TextContent("筛选：全部", "small")])',
  "```",
  'Buttons can chain steps: `Action([@Set($page, "detail"), @Reset($form)])`. Show live state via',
  'concatenation (`TextContent("共 " + $count + " 条")`) and gate sections with ternaries (`$showEdit ? editForm : null`).',
].join("\n");

/** Build the component prompt from the official library (exported for tests). */
export async function buildDesignerPrompt() {
  const { openuiLibrary, openuiPromptOptions } = await import("@openuidev/react-ui/genui-lib");

  // 2026-09-07: both flags were previously absent, so the generated rules
  // never taught $variables/@Set/@Reset or Query/Mutation — the model could
  // only emit stacked static screens. `bindings` documents $vars + @Set/
  // @Reset; `toolCalls` documents the Query workflow against the tool list
  // below (the renderer's tool-provider implements exactly these design.*
  // tools).
  const fullPrompt = openuiLibrary.prompt({
    ...openuiPromptOptions,
    bindings: true,
    toolCalls: true,
    tools: [
      "design.readWiki",
      "design.listWikiPages",
      "design.projectRoot",
      "design.gitStatus",
      "design.listCode",
      "design.readCode",
      "design.memorySearch",
    ],
    examples: [...(openuiPromptOptions.examples ?? []), DESIGNER_EXAMPLE],
    additionalRules: [...(openuiPromptOptions.additionalRules ?? []), ...DESIGNER_ADDITIONAL_RULES],
    editMode: false,
  });

  // library.prompt() opens with a standalone-agent system preamble ("Your
  // ENTIRE response must be valid openui-lang...") that contradicts our
  // tool-call flow — the LLM must call render_openui, not reply in raw DSL.
  // Keep everything from the Syntax Rules onward.
  const syntaxIndex = fullPrompt.indexOf("## Syntax Rules");
  return syntaxIndex > 0 ? fullPrompt.slice(syntaxIndex) : fullPrompt;
}

/** Replace the SKILL.md component-table section with the generated prompt. */
export function applyPromptToSkill(skillMd, prompt) {
  const wrapped = `## Available components\n\n<!-- BEGIN generated component prompt (npm run openui:prompt) -->\n${prompt}\n<!-- END generated component prompt -->\n`;
  // The generated prompt itself contains ## headings, so re-runs must match
  // against the END sentinel rather than the next heading.
  const sentinelRegex = /## Available components[\s\S]*?<!-- END generated component prompt -->/;
  if (sentinelRegex.test(skillMd)) {
    return skillMd.replace(sentinelRegex, wrapped.trimEnd());
  }
  // First migration from a hand-written table: up to the next ## heading.
  const legacyRegex = /## Available components[\s\S]*?(?=\n## )/;
  if (!legacyRegex.test(skillMd)) {
    throw new Error("'## Available components' section not found in SKILL.md");
  }
  return skillMd.replace(legacyRegex, wrapped);
}

async function main() {
  const prompt = await buildDesignerPrompt();

  if (process.argv.includes("--write")) {
    let content = readFileSync(SKILL_PATH, "utf8");
    content = applyPromptToSkill(content, prompt);
    writeFileSync(SKILL_PATH, content, "utf8");
    console.log(`[generate-openui-prompt] updated ${SKILL_PATH}`);
  } else {
    console.log(prompt);
  }
}

// Only run main when invoked directly (tests import the helpers above).
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(`[generate-openui-prompt] failed: ${err.message}`);
    process.exit(1);
  });
}
