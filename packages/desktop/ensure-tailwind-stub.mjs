// Ensure the generated Tailwind script stub exists so a clean checkout (or a
// checkout that just ran `clean:artifacts`) can still typecheck and bundle.
// build.mjs overwrites this file with the real vendored JIT script on every
// desktop build; this script only creates the empty-string fallback when the
// file is missing, so it is idempotent and safe to run before any gate.
//
// Used by desktop:ensure-stub, which is a prerequisite of `typecheck`,
// `desktop:build`, and `desktop:dev` so the import in DesignPreview.tsx
// always resolves.
import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(__dirname, "src", "generated", "tailwind-script.ts");

if (!existsSync(outPath)) {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(
    outPath,
    '// AUTO-GENERATED by build.mjs — do not edit.\n// Committed stub: empty default so typecheck/bundle work before the\n// desktop build vendors the real Tailwind JIT script. build.mjs overwrites\n// this file at build time.\nexport default "";\n'
  );
  console.log("[desktop] ensured generated/tailwind-script.ts stub");
}
